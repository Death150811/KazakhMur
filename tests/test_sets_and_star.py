"""Множества (жиын) и «звёздочные» параметры/аргументы: поведение Python-интерпретатора."""
import pytest

from conftest import run, run_err


def test_set_basics_and_order():
    assert run('жаз(жиын([3, 1, 3, 2, 1]), ұзындық(жиын("қазақ")), түр(жиын())).') == 'жиын([3, 1, 2]) 3 жиын\n'
    assert run("жаз(логика(жиын()), логика(жиын([0]))).") == "жалған ақиқат\n"
    assert run("жаз(жиын([1, 1.0, ақиқат])).") == "жиын([1])\n"  # 1 == 1.0 == ақиқат, как ключи словаря


def test_set_membership_and_equality():
    assert run("жаз(2 ішінде жиын([1, 2]), 5 емес ішінде жиын([1, 2])).") == "ақиқат ақиқат\n"
    assert run("жаз(жиын([1, 2]) == жиын([2, 1]), жиын([1]) == [1], жиын() == жиын()).") == "ақиқат жалған ақиқат\n"


def test_set_methods():
    code = ("айным а = жиын([1, 2, 3]).\nа.қос(4).\nа.өшір(1).\n"
            "жаз(а, а.бірлестір([9]), а.қиылыс([3, 4, 5]), а.айырма([2]), а.ішкіжиын([2, 3, 4, 5]), а.көшір()).")
    assert run(code) == "жиын([2, 3, 4]) жиын([2, 3, 4, 9]) жиын([3, 4]) жиын([3, 4]) ақиқат жиын([2, 3, 4])\n"


def test_set_iteration_is_a_snapshot():
    code = "айным а = жиын([1, 2]).\nәрбір x ішінде а:\n    а.қос(x + 10).\nжаз(а)."
    assert run(code) == "жиын([1, 2, 11, 12])\n"


def test_set_rejects_mutable_elements_and_bad_operations():
    assert "изменяемое" in run_err("жиын([[1]]).").message
    assert "изменяемое" in run_err("жиын().қос({}).").message
    assert "нет в множестве" in run_err("жиын([1]).өшір(2).").message
    assert "индексацию" in run_err("жиын([1])[0].").message
    assert "Нельзя сравнить" in run_err("жиын([1]) < жиын([2]).").message
    assert "словаря" in run_err("{жиын([1]): 2}.").message


def test_rest_and_kwrest_parameters():
    code = "функ ф(а, б = 2, *р, **н):\n    қайтар [а, б, р, н].\nжаз(ф(1), ф(1, 5, 6, 7), ф(1, х = 3), ф(1, 5, 6, ж = 7))."
    assert run(code) == '[1, 2, (), {}] [1, 5, (6, 7), {}] [1, 2, (), {"х": 3}] [1, 5, (6,), {"ж": 7}]\n'
    assert run("айным ф = функ(*а): ұзындық(а).\nжаз(ф(), ф(1, 2, 3)).") == "0 3\n"


def test_spread_in_calls():
    code = ('функ қ(а, б, в = 0):\n    қайтар а + б + в.\n'
            'жаз(қ(*[1, 2]), қ(1, *(2, 3)), қ(**{"а": 1, "б": 2}), қ(1, **{"б": 5, "в": 6}), максимум(*[3, 9, 2])).')
    assert run(code) == "3 6 3 12 9\n"


def test_star_errors():
    assert "не менее" in run_err("функ ф(а, *р):\n    өткіз.\nф().").message
    assert "нужна коллекция" in run_err("функ ф(*р):\n    өткіз.\nф(*5).").message
    assert "нужен сөздік" in run_err("функ ф(**н):\n    өткіз.\nф(**[1]).").message
    assert "передан дважды" in run_err('функ ф(**н):\n    өткіз.\nф(х = 1, **{"х": 2}).').message
    assert "должны быть мәтін" in run_err("функ ф(**н):\n    өткіз.\nф(**{1: 2}).").message


@pytest.mark.parametrize("code, fragment", [
    ("функ ф(*р, а):\n    өткіз.", "после «*» или «**»"),
    ("функ ф(*а, *б):\n    өткіз.", "уже есть"),
    ("функ ф(**н, *р):\n    өткіз.", "должен стоять перед"),
    ("функ ф(**н, **м):\n    өткіз.", "уже есть"),
    ("функ ф(*р = 1):\n    өткіз.", "по умолчанию"),
    ("функ ф(а):\n    өткіз.\nф(а = 1, *[2]).", "Позиционный аргумент после именованного"),
])
def test_star_syntax_errors(code, fragment):
    assert fragment in run_err(code).message
